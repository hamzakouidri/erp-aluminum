import 'dart:convert';

import 'package:database_data/Commande/devis_builder.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('Devis uses only the saved invoice table title and details', () async {
    SharedPreferences.setMockInitialValues({'app_language': 0});

    final data = await DevisBuilder.build(
      order: {
        'id': 101,
        'created_at': '2026-07-28',
        'firstname': 'Test',
        'lastname': 'Client',
      },
      items: [
        {
          'id': 501,
          'game': 'Series generated by the system',
          'window_type': 'sliding',
          'largeur': 1200,
          'hauteur': 1400,
          'quantity': 2,
          'price': 25000.0,
          'color': 'white',
          'partitions_json': jsonEncode({
            'width': 1200,
            'height': 1400,
            'seriesName': 'Automatic series',
            'zones': [
              {'content': 'slidingSash'},
            ],
            'manualNameOverride': 'Visible edited item',
            'description': 'Visible detail one\nVisible detail two',
            'invoiceTableEdited': true,
          }),
        },
      ],
      workshop: const DevisWorkshopInfo(
        name: 'Workshop',
        phone: '',
        address: '',
      ),
    );

    expect(data.items, hasLength(1));
    expect(data.items.single.title, 'Visible edited item');
    expect(
      data.items.single.details,
      ['Visible detail one', 'Visible detail two'],
    );
    expect(
      data.items.single.details.join(' '),
      isNot(contains('Automatic series')),
    );
  });

  test(
    'Devis preserves edited text when the document language is French',
    () async {
      SharedPreferences.setMockInitialValues({'app_language': 1});

      final data = await DevisBuilder.build(
        order: {
          'id': 102,
          'created_at': '2026-07-28',
          'firstname': 'Test',
          'lastname': 'Client',
        },
        items: [
          {
            'id': 502,
            'game': 'Série automatique',
            'window_type': 'sliding',
            'largeur': 1200,
            'hauteur': 1400,
            'quantity': 1,
            'price': 25000.0,
            'color': 'white',
            'partitions_json': jsonEncode({
              'width': 1200,
              'height': 1400,
              'seriesName': 'Série automatique',
              'zones': [
                {'content': 'slidingSash'},
              ],
              'manualNameOverride': 'Nom modifié',
              'description':
                  'Gamme: texte modifié\nCouleur Profil: couleur modifiée',
              'invoiceTableEdited': true,
            }),
          },
        ],
        workshop: const DevisWorkshopInfo(
          name: 'Workshop',
          phone: '',
          address: '',
        ),
      );

      expect(data.items.single.title, 'Nom modifié');
      expect(
        data.items.single.details,
        ['Gamme: texte modifié', 'Couleur Profil: couleur modifiée'],
      );
    },
  );

  test('a tunnel box on a designed window stays a normal window invoice line', () async {
    SharedPreferences.setMockInitialValues({'app_language': 0});

    final data = await DevisBuilder.build(
      order: {
        'id': 103,
        'created_at': '2026-07-28',
        'firstname': 'Test',
        'lastname': 'Client',
      },
      items: [
        {
          'id': 503,
          'game': '4000 - نافذة بضلفة واحدة',
          'window_type': 'mixed',
          'largeur': 1200,
          'hauteur': 1400,
          'quantity': 1,
          'price': 25000.0,
          'color': 'white',
          'partitions_json': jsonEncode({
            'width': 1200,
            'height': 1400,
            'isDesignDrawing': true,
            'isCaissonTunnel': true,
            'showWall': true,
            'seriesName': '4000',
            'zones': [
              {'content': 'singleSash'},
            ],
            'description': 'نافذة كاملة مع صندوق نفق',
          }),
        },
      ],
      workshop: const DevisWorkshopInfo(
        name: 'Workshop',
        phone: '',
        address: '',
      ),
    );

    expect(data.items.single.title, isNot('Caisson Tunnel'));
    expect(data.items.single.details.join(' '), isNot(contains('Kit:')));
  });
}
