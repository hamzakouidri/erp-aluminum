-- Price sharing from the application administrator to every workshop.
--
-- Selling prices are workshop data (SectionColorPrices, SeriesColorPrices,
-- AccessoryColorPrices, ...) and are deliberately excluded from the global
-- catalogue. The administrator therefore publishes a price snapshot per
-- category here; each workshop manager is notified and decides to apply or
-- ignore it. An applied snapshot is written into the manager's local price
-- tables and reaches the workers through the normal workshop sync.
--
-- Run this file once in the Supabase SQL Editor.

create table if not exists public.shared_price_publications (
  id bigint generated by default as identity primary key,
  category text not null,
  payload jsonb not null,
  row_count integer not null default 0,
  note text not null default '',
  published_by uuid references auth.users(id) on delete set null,
  published_at timestamptz not null default now()
);

create index if not exists shared_price_publications_category_idx
  on public.shared_price_publications (category, published_at desc);

alter table public.shared_price_publications enable row level security;

drop policy if exists "members read price publications" on public.shared_price_publications;
create policy "members read price publications"
on public.shared_price_publications for select
to authenticated
using (true);

drop policy if exists "app admin publishes prices" on public.shared_price_publications;
create policy "app admin publishes prices"
on public.shared_price_publications for insert
to authenticated
with check (public.is_app_admin());

drop policy if exists "app admin deletes price publications" on public.shared_price_publications;
create policy "app admin deletes price publications"
on public.shared_price_publications for delete
to authenticated
using (public.is_app_admin());

revoke all on public.shared_price_publications from anon;
grant select, insert, delete on public.shared_price_publications to authenticated;

-- One decision per workshop and publication, shared by all managers of the
-- workshop so the prompt is not shown again on their other devices.
create table if not exists public.price_publication_decisions (
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  publication_id bigint not null
    references public.shared_price_publications(id) on delete cascade,
  status text not null check (status in ('applied', 'dismissed')),
  decided_by uuid references auth.users(id) on delete set null,
  decided_at timestamptz not null default now(),
  primary key (workshop_id, publication_id)
);

alter table public.price_publication_decisions enable row level security;

drop policy if exists "managers manage price decisions" on public.price_publication_decisions;
create policy "managers manage price decisions"
on public.price_publication_decisions for all
to authenticated
using (
  exists (
    select 1 from public.workshop_members m
    where m.workshop_id = price_publication_decisions.workshop_id
      and m.user_id = auth.uid()
  )
)
with check (
  exists (
    select 1 from public.workshop_members m
    where m.workshop_id = price_publication_decisions.workshop_id
      and m.user_id = auth.uid()
      and m.role in ('owner', 'manager', 'co_manager', 'admin')
  )
);

revoke all on public.price_publication_decisions from anon;
grant select, insert, update, delete on public.price_publication_decisions to authenticated;
