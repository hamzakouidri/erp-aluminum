  INSERT INTO public.workshop_sync_rows (
    workshop_id,
    table_name,
    row_id,
    payload,
    updated_at,
    device_id,
    revision
  )
  SELECT 
    target_id,
    r.table_name,
    r.row_id,
    r.payload,
    now(),
    r.device_id,
    r.revision + 1
  FROM public.workshop_sync_rows r
  WHERE r.workshop_id <> target_id
    AND r.deleted_at IS NULL
    AND r.table_name NOT IN ('WorkshopProfile', 'WorkshopCatalogConfiguration')
