DECLARE
  target_id uuid;
  moved_count int := 0;
BEGIN
  -- ????? ???? ?????? ????????? ???????
  SELECT id INTO target_id
  FROM public.workshops
  WHERE upper(join_code) LIKE '9DAC0E%' 
     OR upper(code) LIKE '9DAC0E%'
     OR id::text LIKE '9dac0e%'
  LIMIT 1;

  IF target_id IS NULL THEN
    RAISE EXCEPTION '?? ??? ?????? ??? ???? ????? ????? 9dac0e. ???? ?????? ?? ??? ?????? ?? ??????';
  END IF;

  RAISE NOTICE '?? ?????? ??? ???? ?????? ????????? ?????: %', target_id;

