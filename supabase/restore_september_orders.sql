SELECT 
    w.id AS workshop_uuid,
    w.code AS workshop_code,
    w.join_code AS workshop_join_code,
    w.name AS workshop_name,
    r.table_name,
    r.row_id,
    r.payload->>'client_name' AS client_name,
    r.payload->>'code_commande' AS code_commande,
    r.payload->>'date' AS order_date,
    r.payload->>'date_creation' AS date_creation,
    r.updated_at
FROM public.workshop_sync_rows r
JOIN public.workshops w ON w.id = r.workshop_id
WHERE r.table_name IN ('Commande', 'commandes')
ORDER BY r.updated_at DESC;

