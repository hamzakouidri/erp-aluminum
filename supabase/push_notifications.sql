create table if not exists public.device_push_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  token text not null unique,
  platform text not null default 'android',
  updated_at timestamptz not null default now()
);

create index if not exists device_push_tokens_target_idx
  on public.device_push_tokens (workshop_id, user_id);

alter table public.device_push_tokens enable row level security;

drop policy if exists "users manage own push tokens" on public.device_push_tokens;
create policy "users manage own push tokens"
on public.device_push_tokens for all
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.workshop_members m
    where m.workshop_id = device_push_tokens.workshop_id
      and m.user_id = auth.uid()
  )
);

revoke all on public.device_push_tokens from anon;
grant select, insert, update, delete on public.device_push_tokens to authenticated;

create table if not exists public.notification_preferences (
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (user_id, event_type)
);

alter table public.notification_preferences enable row level security;
drop policy if exists "users manage own notification preferences" on public.notification_preferences;
create policy "users manage own notification preferences"
on public.notification_preferences for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);
revoke all on public.notification_preferences from anon;
grant select, insert, update, delete on public.notification_preferences to authenticated;
